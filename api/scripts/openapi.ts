/**
 * Generates openapi/openapi.yaml from the zod schemas registered by the module routers.
 *   npm run openapi          write the file
 *   npm run openapi:check    fail if the committed file is out of date (used in CI)
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';

// Generating the spec must not need real secrets or a database.
process.env.DATABASE_URL ??= 'postgresql://openapi:openapi@localhost:5432/openapi';
process.env.JWT_ACCESS_SECRET ??= 'openapi-generation-only-secret-000000000000';
process.env.TOKEN_HASH_PEPPER ??= 'openapi-generation-only-pepper-000000000000';
process.env.DATA_ENCRYPTION_KEY ??= Buffer.alloc(32).toString('base64');
process.env.NODE_ENV ??= 'test';

const { moduleRouters } = await import('../src/app.js');
const { generateOpenApiDocument } = await import('../src/lib/openapi.js');

if (moduleRouters.length === 0) throw new Error('No routers registered');

const doc = generateOpenApiDocument();
const yaml = `# GENERATED by \`npm run openapi\` - do not edit.\n${stringify(doc, { lineWidth: 0 })}`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../openapi/openapi.yaml');

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== yaml) {
    console.error('openapi/openapi.yaml is out of date. Run `npm run openapi` and commit the result.');
    process.exit(1);
  }
  console.log('openapi/openapi.yaml is up to date.');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, yaml, 'utf8');
  console.log(`Wrote ${out} (${Object.keys(doc.paths ?? {}).length} paths)`);
}
process.exit(0);
