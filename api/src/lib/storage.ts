import { createReadStream } from 'node:fs';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { GetObjectCommand, HeadObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import express from 'express';
import type { Router } from 'express';
import { env } from '../config/env.js';
import { hmacHash, safeEqualHex } from './crypto.js';
import { API_BASE_PATH } from './openapi.js';

/**
 * Private file storage with short-lived signed URLs (CLAUDE.md §7: ≤ 10 minutes).
 * Clients upload directly to the signed URL; the API only stores the object key.
 */
export interface SignedUrl {
  /** Absolute URL, or a path starting with '/' (local driver) that the caller prefixes with the API origin. */
  url: string;
  method: 'PUT' | 'GET';
  headers: Record<string, string>;
  expiresAt: Date;
}

export interface StorageService {
  presignPut(key: string, contentType: string): Promise<SignedUrl>;
  presignGet(key: string): Promise<SignedUrl>;
  exists(key: string): Promise<boolean>;
  /** Server-side write (generated reports, uploaded payslips). */
  putObject(key: string, body: Buffer, contentType: string): Promise<void>;
}

/** Object keys are generated by the API; this guards the local driver against path tricks. */
export const OBJECT_KEY_PATTERN = /^[a-z0-9][a-z0-9/_.-]{0,255}$/;
export function isSafeKey(key: string): boolean {
  return OBJECT_KEY_PATTERN.test(key) && !key.includes('..') && !key.includes('//');
}

const expiry = () => new Date(Date.now() + env.SIGNED_URL_TTL_SECONDS * 1000);

// ─────────────────────────────── S3 / MinIO ───────────────────────────────

export class S3StorageService implements StorageService {
  private readonly client = new S3Client({
    region: env.S3_REGION,
    endpoint: env.S3_ENDPOINT,
    forcePathStyle: env.S3_FORCE_PATH_STYLE,
    credentials:
      env.S3_ACCESS_KEY_ID && env.S3_SECRET_ACCESS_KEY
        ? { accessKeyId: env.S3_ACCESS_KEY_ID, secretAccessKey: env.S3_SECRET_ACCESS_KEY }
        : undefined,
  });

  async presignPut(key: string, contentType: string): Promise<SignedUrl> {
    const url = await getSignedUrl(this.client, new PutObjectCommand({ Bucket: env.S3_BUCKET, Key: key, ContentType: contentType }), {
      expiresIn: env.SIGNED_URL_TTL_SECONDS,
    });
    return { url, method: 'PUT', headers: { 'Content-Type': contentType }, expiresAt: expiry() };
  }

  async presignGet(key: string): Promise<SignedUrl> {
    const url = await getSignedUrl(this.client, new GetObjectCommand({ Bucket: env.S3_BUCKET, Key: key }), {
      expiresIn: env.SIGNED_URL_TTL_SECONDS,
    });
    return { url, method: 'GET', headers: {}, expiresAt: expiry() };
  }

  async exists(key: string): Promise<boolean> {
    try {
      await this.client.send(new HeadObjectCommand({ Bucket: env.S3_BUCKET, Key: key }));
      return true;
    } catch {
      return false;
    }
  }

  async putObject(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.client.send(new PutObjectCommand({ Bucket: env.S3_BUCKET, Key: key, Body: body, ContentType: contentType }));
  }
}

// ──────────────────────── Local disk (dev machines only) ────────────────────────

export const LOCAL_STORAGE_PATH = '/storage/local';

function localSignature(op: 'put' | 'get', key: string, exp: number, contentType: string): string {
  return hmacHash(`storage:${op}:${key}:${exp}:${contentType}`, env.TOKEN_HASH_PEPPER);
}

/**
 * Emulates presigned URLs on the local file system: the URL carries an HMAC over (op, key, expiry,
 * content type) and is served by {@link localStorageRouter}. Refused in production by env validation.
 */
export class LocalStorageService implements StorageService {
  readonly root = resolve(env.LOCAL_STORAGE_DIR);

  pathOf(key: string): string {
    if (!isSafeKey(key)) throw new Error('Unsafe object key');
    return join(this.root, ...key.split('/'));
  }

  private sign(op: 'put' | 'get', key: string, contentType: string): SignedUrl {
    const expiresAt = expiry();
    const exp = Math.floor(expiresAt.getTime() / 1000);
    const sig = localSignature(op, key, exp, contentType);
    const qs = new URLSearchParams({ op, exp: String(exp), ct: contentType, sig });
    return {
      url: `${API_BASE_PATH}${LOCAL_STORAGE_PATH}/${key}?${qs.toString()}`,
      method: op === 'put' ? 'PUT' : 'GET',
      headers: op === 'put' ? { 'Content-Type': contentType } : {},
      expiresAt,
    };
  }

  async presignPut(key: string, contentType: string): Promise<SignedUrl> {
    return this.sign('put', key, contentType);
  }

  async presignGet(key: string): Promise<SignedUrl> {
    let contentType = 'application/octet-stream';
    try {
      contentType = (await readFile(`${this.pathOf(key)}.meta`, 'utf8')).trim() || contentType;
    } catch {
      // missing meta → default type
    }
    return this.sign('get', key, contentType);
  }

  async exists(key: string): Promise<boolean> {
    try {
      return (await stat(this.pathOf(key))).isFile();
    } catch {
      return false;
    }
  }

  async putObject(key: string, body: Buffer, contentType: string): Promise<void> {
    const file = this.pathOf(key);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, body);
    await writeFile(`${file}.meta`, contentType);
  }

  /** Verifies a signed local URL. */
  verify(op: 'put' | 'get', key: string, query: Record<string, unknown>): { contentType: string } | null {
    const exp = Number(query.exp);
    const ct = typeof query.ct === 'string' ? query.ct : '';
    const sig = typeof query.sig === 'string' ? query.sig : '';
    if (query.op !== op || !Number.isFinite(exp) || exp * 1000 < Date.now() || !isSafeKey(key)) return null;
    return safeEqualHex(localSignature(op, key, exp, ct), sig) ? { contentType: ct } : null;
  }
}

/**
 * Serves signed PUT/GET for the local driver. Mounted at `${API_BASE_PATH}${LOCAL_STORAGE_PATH}` only
 * when STORAGE_DRIVER=local. Authorisation is the URL signature (like an S3 presigned URL), so these
 * are deliberately plain Express routes outside ModuleRouter (they take a raw body and are not part of the API spec).
 */
export function localStorageRouter(service: LocalStorageService): Router {
  const router = express.Router();
  const keyOf = (path: string) => decodeURIComponent(path.replace(/^\//, ''));
  const forbidden = { error: { code: 'INVALID_SIGNATURE', message: 'Signed URL is invalid or expired' } };

  router.put(/.*/, express.raw({ type: () => true, limit: env.MAX_UPLOAD_BYTES }), async (req, res) => {
    const key = keyOf(req.path);
    const ok = service.verify('put', key, req.query);
    if (!ok || req.get('content-type') !== ok.contentType) {
      res.status(403).json(forbidden);
      return;
    }
    await service.putObject(key, Buffer.isBuffer(req.body) ? req.body : Buffer.alloc(0), ok.contentType);
    res.status(200).end();
  });

  router.get(/.*/, async (req, res) => {
    const key = keyOf(req.path);
    const ok = service.verify('get', key, req.query);
    if (!ok || !(await service.exists(key))) {
      res.status(403).json(forbidden);
      return;
    }
    res.setHeader('Content-Type', ok.contentType);
    res.setHeader('Cache-Control', 'private, no-store');
    // The Flutter web app (another origin in dev) loads previews from here; the signature is the authorisation.
    res.setHeader('Cross-Origin-Resource-Policy', 'cross-origin');
    createReadStream(service.pathOf(key)).pipe(res);
  });
  return router;
}

let instance: StorageService | undefined;

export function getStorageService(): StorageService {
  instance ??= env.STORAGE_DRIVER === 'local' ? new LocalStorageService() : new S3StorageService();
  return instance;
}

/** Test hook. */
export function setStorageService(service: StorageService): void {
  instance = service;
}
