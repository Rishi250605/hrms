/** Excel / PDF downloads of the attendance report (§9.1): generated server-side, stored privately, signed URL, audited. */

const FILL: Record<string, string> = { P: 'FFC8E6C9', A: 'FFFFCDD2', HD: 'FFFFE0B2', L: 'FFBBDEFB', OD: 'FFD1C4E9', WO: 'FFE0E0E0', H: 'FFE0E0E0' };
const baseCode = (c: string) => c.replace(/[*!]$/, '');

const SUMMARY_COLUMNS: [keyof Report['rows'][number]['summary'], string][] = [
  ['present', 'Present'],
  ['absent', 'Absent'],
  ['halfDay', 'Half days'],
  ['leave', 'Leave'],
  ['onDuty', 'On duty'],
  ['weeklyOff', 'Weekly off'],
  ['holiday', 'Holiday'],
  ['pending', 'Pending approval'],
  ['rejected', 'Rejected'],
  ['notMarked', 'Not marked'],
];

function header(report: Report, by: string) {
  return {
    title: `Attendance — ${report.businessUnits.map((b) => b.name).join(', ')}`,
    period: `Period: ${report.from} to ${report.to}`,
    generated: `Generated by ${by} on ${todayIst()} ${istTimeOf(new Date(report.generatedAt))} IST`,
  };
}

export async function toXlsx(report: Report, by: string): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = by;
  wb.created = new Date(report.generatedAt);
  const h = header(report, by);

  const muster = wb.addWorksheet('Muster', { views: [{ state: 'frozen', xSplit: 4, ySplit: 5 }] });
  muster.addRow([h.title]).font = { bold: true, size: 14 };
  muster.addRow([h.period]);
  muster.addRow([h.generated]);
  muster.addRow([LEGEND.map((l) => `${l.code} = ${l.label}`).join('   ')]).font = { italic: true, size: 9 };
  const head = muster.addRow(['Emp code', 'Name', 'Role', 'BU', ...report.days.map((d) => Number(d.slice(8)))]);
  head.font = { bold: true };
  for (const r of report.rows) {
    const row = muster.addRow([r.employee.empCode, r.employee.name, r.employee.role ?? r.employee.category, r.businessUnitCode ?? '', ...r.codes]);
    r.codes.forEach((c, i) => {
      const fill = FILL[baseCode(c)];
      const cell = row.getCell(5 + i);
      cell.alignment = { horizontal: 'center' };
      if (fill) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: fill } };
      if (c.endsWith('*')) cell.font = { italic: true, color: { argb: 'FF8D6E00' } };
      if (c.endsWith('!')) cell.font = { strike: true, color: { argb: 'FFB71C1C' } };
    });
  }
  muster.getColumn(1).width = 11;
  muster.getColumn(2).width = 26;
  muster.getColumn(3).width = 20;
  muster.getColumn(4).width = 7;
  report.days.forEach((_, i) => (muster.getColumn(5 + i).width = 4.5));

  const summary = wb.addWorksheet('Summary', { views: [{ state: 'frozen', ySplit: 4 }] });
  summary.addRow([h.title]).font = { bold: true, size: 14 };
  summary.addRow([h.period]);
  summary.addRow([h.generated]);
  summary.addRow(['Emp code', 'Name', 'Role', 'BU', ...SUMMARY_COLUMNS.map(([, l]) => l)]).font = { bold: true };
  for (const r of report.rows) {
    summary.addRow([r.employee.empCode, r.employee.name, r.employee.role ?? r.employee.category, r.businessUnitCode ?? '', ...SUMMARY_COLUMNS.map(([k]) => r.summary[k])]);
  }
  summary.columns.forEach((c, i) => (c.width = i === 1 ? 26 : i < 4 ? 12 : 10));
  return Buffer.from(await wb.xlsx.writeBuffer());
}

export function toPdf(report: Report, by: string): Promise<Buffer> {
  const h = header(report, by);
  const doc = new PDFDocument({ size: 'A3', layout: 'landscape', margin: 24, info: { Title: h.title, Author: by } });
  const chunks: Buffer[] = [];
  doc.on('data', (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const left = doc.page.margins.left;
  const width = doc.page.width - left - doc.page.margins.right;
  const fixed = [52, 130, 64];
  const totals = ['P', 'A', 'HD', 'L', 'OD'];
  const dayW = (width - fixed.reduce((a, b) => a + b, 0) - totals.length * 22) / report.days.length;
  const rowH = 13;
  const cols = [...fixed, ...report.days.map(() => dayW), ...totals.map(() => 22)];

  const drawRow = (cells: string[], y: number, opts: { bold?: boolean; fills?: (string | undefined)[] } = {}) => {
    let x = left;
    doc.font(opts.bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(7);
    cells.forEach((text, i) => {
      const w = cols[i]!;
      const fill = opts.fills?.[i];
      if (fill) doc.rect(x, y, w, rowH).fill(`#${fill.slice(2)}`).fillColor('black');
      doc.rect(x, y, w, rowH).lineWidth(0.3).strokeColor('#9e9e9e').stroke();
      doc.fillColor('black').text(text, x + 2, y + 3, { width: w - 4, height: rowH - 2, align: i < 3 ? 'left' : 'center', lineBreak: false, ellipsis: true });
      x += w;
    });
  };
  const pageHeader = () => {
    doc.font('Helvetica-Bold').fontSize(13).text(h.title, left, doc.page.margins.top);
    doc.font('Helvetica').fontSize(8).text(`${h.period}    ${h.generated}`);
    doc.fontSize(7).text(LEGEND.map((l) => `${l.code} = ${l.label}`).join('   '));
    const y = doc.y + 4;
    drawRow(['Code', 'Name', 'Role', ...report.days.map((d) => d.slice(8)), ...totals], y, { bold: true });
    return y + rowH;
  };

  let y = pageHeader();
  for (const r of report.rows) {
    if (y + rowH > doc.page.height - doc.page.margins.bottom) {
      doc.addPage();
      y = pageHeader();
    }
    const s = r.summary;
    drawRow(
      [r.employee.empCode, r.employee.name, (r.employee.role ?? r.employee.category).replace(/_/g, ' '), ...r.codes, String(s.present), String(s.absent), String(s.halfDay), String(s.leave), String(s.onDuty)],
      y,
      { fills: [undefined, undefined, undefined, ...r.codes.map((c) => FILL[baseCode(c)])] },
    );
    y += rowH;
  }
  if (report.rows.length === 0) doc.font('Helvetica').fontSize(9).text('No attendance in this selection.', left, y + 6);
  doc.end();
  return done;
}

const TYPES = {
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  pdf: 'application/pdf',
} as const;

export async function exportAttendance(
  user: AuthUser,
  q: Parameters<typeof attendanceReport>[1] & { format: 'xlsx' | 'pdf' },
  origin: string,
  ctx: RequestContext,
) {
  const { format, ...filters } = q;
  const report = await attendanceReport(user, filters);
  const body = format === 'xlsx' ? await toXlsx(report, user.name) : await toPdf(report, user.name);
  const bu = report.businessUnits.length === 1 ? report.businessUnits[0]!.code : 'ALL';
  const fileName = `attendance-${bu}-${report.from}-to-${report.to}.${format}`;
  const key = `reports/${todayIst()}/${randomUUID()}.${format}`;
  await getStorageService().putObject(key, body, TYPES[format]);
  // TODO(business): retention of generated report files (purge job once the storage driver can delete).
  await audit.record(prisma, ctx, {
    action: 'report.attendance.export',
    entityType: 'Report',
    entityId: key,
    after: { format, ...filters, rows: report.rows.length, from: report.from, to: report.to },
  });
  return { ...(await signedUrlFor(key, origin)), fileName, contentType: TYPES[format] };
}
